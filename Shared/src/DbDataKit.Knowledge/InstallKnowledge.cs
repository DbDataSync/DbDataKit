using DbDataKit.Config.Yaml;

namespace DbDataKit.Knowledge;

/// <summary>
/// The install's knowledge project (plan 27a KN35, plan 27 section 3.5c item 6): the home of what every agent of the install should know, in folders that set their scope by place. <c>policy/</c> holds the administrators' own text: guardrails they
/// own. Settings (prompting minimums, limits, data rules) are not text and live in <c>agent-policy/1</c>; a setting written in a knowledge file is refused saying so (<see cref="KnowledgeItemLoader"/>).
/// </summary>
public static class InstallKnowledge
{
    /// <summary>The owner of the administrators' text.</summary>
    public const string AdministratorsOwner = "administrators";

    /// <summary>The folder of the administrators' text.</summary>
    public const string PolicyFolder = "policy";

    public const string PolicyRule = "DBD-KNW-020";

    /// <summary>The template: every file of a new install knowledge project, by relative path. The items are examples an administrator replaces.</summary>
    public static IReadOnlyDictionary<string, string> Template { get; } = new SortedDictionary<string, string>(StringComparer.Ordinal)
    {
        ["_knowledge.yml"] = """
            knowledge: 1
            # everything in this project is about the whole install unless a folder below says otherwise
            defaults:
              about:
                - install: true
              owner: administrators
            """,
        ["README.md"] = """
            # The install's knowledge

            What every agent of this install should know, as short Markdown files with a front matter (`knowledge: 1`, `role`, who owns it).

            - `shared/` is about the whole install.
            - `build/` is about work on Build, `sync-and-build/` about work on Build and Sync (`_knowledge.yml` in each folder sets that).
            - `policy/` is the administrators' own text: guardrails they own. Policy *settings* (prompting minimums, limits, data rules for cloud providers) are not text and are edited as the install policy in the console.

            Replace the examples. A file here changes what agents do the moment it is published to a channel they use.
            """,
        ["shared/house-style.md"] = """
            ---
            knowledge: 1
            title: House style for names and answers
            role: instruction
            ---
            Write names in English. Say what you did in one sentence before you show detail. When a number comes from a query, say which query.
            """,
        ["build/_knowledge.yml"] = """
            knowledge: 1
            defaults:
              about:
                - product: build
            """,
        ["build/naming.md"] = """
            ---
            knowledge: 1
            title: Naming in Build projects
            role: instruction
            ---
            Facts are named `fct_`, dimensions `dim_`, one model per file.
            """,
        ["sync-and-build/_knowledge.yml"] = """
            knowledge: 1
            defaults:
              about:
                - product: [build, sync]
            """,
        ["sync-and-build/environments.md"] = """
            ---
            knowledge: 1
            title: Our environments and what each is for
            role: reference
            ---
            # Environments

            Replace this with how your install names its environments, which one may be written to, and who approves a change to production.
            """,
        ["policy/_knowledge.yml"] = """
            knowledge: 1
            defaults:
              role: guardrail
              owner: administrators
            """,
        ["policy/generated-answers.md"] = """
            ---
            knowledge: 1
            title: Say that an answer is generated
            for:
              audience: front-end
            ---
            Say that an answer was generated by an agent and may be wrong; give the source of every number.
            """,
    }.ToDictionary(p => p.Key, p => p.Value + "\n");

    /// <summary>Writes the template into an empty or missing folder. A folder that has files is refused: a template never overwrites.</summary>
    public static void Write(string directory)
    {
        if (Directory.Exists(directory) && Directory.EnumerateFileSystemEntries(directory).Any())
            throw new InvalidOperationException($"'{directory}' is not empty; the install knowledge project is made in an empty folder.");
        foreach (var (path, text) in Template)
        {
            var full = Path.Combine(directory, path.Replace('/', Path.DirectorySeparatorChar));
            Directory.CreateDirectory(Path.GetDirectoryName(full)!);
            File.WriteAllText(full, text);
        }
    }

    /// <summary>The rule of the policy folder: every item in it is a guardrail owned by the administrators (as a default or in the item), so what an administrator writes there is policy and nobody else's.</summary>
    public static IReadOnlyList<ConfigDiagnostic> CheckPolicyFolder(KnowledgeProject project)
    {
        var errors = new List<ConfigDiagnostic>();
        foreach (var item in project.Items.Where(i => i.Id.StartsWith(PolicyFolder + "/", StringComparison.Ordinal)))
        {
            if (item.Role != KnowledgeRole.Guardrail)
                errors.Add(DefaultDiagnosticCatalog.Instance.Create(PolicyRule, item.File, 1, 1, $"'{item.Id}' is in the policy folder and is a {item.Role.ToString().ToLowerInvariant()}: the administrators' text is guardrails.", "Set `role: guardrail`, or move the file out of `policy/`."));
            if (!string.Equals(item.Owner, AdministratorsOwner, StringComparison.Ordinal))
                errors.Add(DefaultDiagnosticCatalog.Instance.Create(PolicyRule, item.File, 1, 1, $"'{item.Id}' is in the policy folder and its owner is {(item.Owner is null ? "not set" : $"'{item.Owner}'")}: the administrators own it.", $"Set `owner: {AdministratorsOwner}`."));
        }
        return errors;
    }
}
