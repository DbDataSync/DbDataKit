using DbDataKit.Agents;
using DbDataKit.Agents.Testing;
using DbDataKit.Cli;
using DbDataKit.Knowledge;
using Microsoft.Extensions.AI;

namespace DbDataKit.Agents.Tests;

/// <summary>The worked example of plan 27 section 3.5a as data: the knowledge K1 to K6, the back-end agent, the workspace on the Build project and the measure that comes into play.</summary>
internal static class WorkedExample
{
    internal static KnowledgeItem Item(string id, string frontMatter, string body)
    {
        var result = KnowledgeItemLoader.Load($"---\nknowledge: 1\ntitle: {id}\nowner: data\n{frontMatter}\n---\n{body}", id, id);
        Assert.True(result.Ok, string.Join('\n', result.Diagnostics));
        return result.Item!;
    }

    internal static readonly KnowledgeItem K1 = Item("K1", "role: instruction\nabout:\n  - build-project: sales-warehouse\nfor: { audience: back-end }", "Facts are named fct_, dimensions dim_; one model per file.");
    internal static readonly KnowledgeItem K2 = Item("K2", "role: guardrail\nabout:\n  - build-project: sales-warehouse\n    folder: models/marts\nfor: { audience: back-end }", "Every dimension has an unknown member (key 0).");
    internal static readonly KnowledgeItem K3 = Item("K3", "role: instruction\nabout:\n  - semantic-model: Sales\n    measure: revenue", "Revenue means net revenue: gross minus returns minus discounts.");
    internal static readonly KnowledgeItem K4 = Item("K4", "role: reference\nabout:\n  - build-project: sales-warehouse\n    model: marts.dim_region", "In 2025 the EMEA region was split into EU and MEA.");
    internal static readonly KnowledgeItem K6 = Item("K6", "role: instruction\nabout:\n  - install: true\nfor: { audience: front-end }", "Say that an answer is generated by an agent.");

    internal static readonly AgentDefinition Agent = AgentDefinitionLoader.Load("agent: 1\nname: build-helper\naudience: back-end\nmodel: { slot: default }\nknowledge: { from: [project, install] }", "agent.yml").Definition!;

    internal static readonly InPlay Workspace = new(new KnowledgeSubject("build-project", ["sales-warehouse"]), Whole: true);
    internal static readonly InPlay Revenue = new(new KnowledgeSubject("semantic-model", ["Sales"], "measure", "revenue"));


    internal static readonly KnowledgeItem[] Items = [K1, K2, K3, K4, K6];

    /// <summary>What the scope matcher gives the back-end agent for what is in play (the sources are not narrowed).</summary>
    internal static BoundKnowledge Bound(params InPlay[] inPlay) => ScopeMatcher.Match(Items, inPlay, new ScopeAudience("back-end", "build-helper"));
}
